"""Real guest-only 2B model acceptance; only runs on isolated CI ISO.

This code runs under the normal guest desktop UID, not root; it calls no host
API, reads no private user files and never executes a model-proposed tool.
"""
import json
import os
from pathlib import Path
import subprocess
import time

from aiws_guest_boundary import require_guest_runtime
from aiws_local_model import LocalPlanner

def main():
    require_guest_runtime()
    marker=Path("/etc/aiws/guest-model-acceptance")
    if marker.is_symlink() or not marker.is_file() or marker.read_text().strip()!="AIWS_MODEL_CI_ONLY=1":
        raise PermissionError("Only isolated test guest may activate model acceptance")
    source=Path("/usr/local/share/aiws/model-preload/manifest.json")
    if not source.is_file():
        raise RuntimeError("Real model was not bundled into guest ISO")
    # A normal user explicitly starts a fixed guest systemd unit, not a shell
    # or privileged command generated by the model.
    subprocess.run(["systemctl","--user","start","aiws-local-model.service"],
                   timeout=15,check=True)
    try:
        planner=LocalPlanner(enabled=True)
        online=False
        begin=time.monotonic()
        for _ in range(300):
            if planner.status()["online"]:
                online=True
                break
            time.sleep(1)
        if not online:
            raise RuntimeError("Bundled model service was not healthy inside guest")
        ready=time.monotonic()-begin
        started=time.monotonic()
        proposal=planner.suggest("请列出当前客户机项目工作区里的文件")
        elapsed=time.monotonic()-started
        if proposal["tool"]!="workspace.tree" or proposal["arguments"].get("path")!=".":
            raise RuntimeError("Real guest model gave an incorrect file inspection proposal")
        receipt={"guest_only":True,"real_guest_model":True,"model":"Qwen3.5-2B-Q4_K_M",
                 "inference":"llama.cpp CPU","cloud_calls":0,"gpu_layers":0,
                 "service_load_seconds":round(ready,2),
                 "first_proposal_seconds":round(elapsed,2),
                 "valid_tool":proposal["tool"],"executed":proposal["executed"]}
        print("AIWS_GUEST_MODEL_INFERENCE_PASS "+json.dumps(receipt,sort_keys=True),flush=True)
    finally:
        subprocess.run(["systemctl","--user","stop","aiws-local-model.service"],
                       timeout=15,check=False)

if __name__=="__main__":
    main()
